"""genui + a local model through Ollama. No cloud, no API key: prompts and data never leave your machine.

Run:  ollama pull qwen3            # or any model you like: llama3.3, gemma3, mistral, ...
      pip install "genui-py[fastapi,openai]" uvicorn
      uvicorn ollama_app:app --reload --port 8000
Works the same with vLLM / LM Studio / llama.cpp server: point OLLAMA_URL at their /v1 endpoint.
"""
import os
from pathlib import Path

from fastapi import FastAPI, Request
from openai import AsyncOpenAI

from genui import Library
from genui.integrations.fastapi import read_run, stream_response

# spec.json is generated by the React frontend (`npm run generate` in examples/fastapi-react/frontend)
# from the same component library the renderer uses, so prompt and UI never drift apart.
SPEC = Path(__file__).resolve().parents[1] / "fastapi-react" / "backend" / "spec.json"
library = Library.from_spec(SPEC)
SYSTEM_PROMPT = library.system_prompt()

# Ollama speaks the OpenAI Chat Completions protocol on localhost. The key is required by the
# client library but ignored by Ollama.
client = AsyncOpenAI(base_url=os.environ.get("OLLAMA_URL", "http://localhost:11434/v1"), api_key="ollama")
MODEL = os.environ.get("MODEL", "qwen3")

app = FastAPI()


@app.post("/api/chat")
async def chat(request: Request):
    run = await read_run(request)
    stream = await client.chat.completions.create(
        model=MODEL,
        messages=[{"role": "system", "content": SYSTEM_PROMPT}, *run.messages],
        stream=True,
    )
    return stream_response(stream, run=run)
