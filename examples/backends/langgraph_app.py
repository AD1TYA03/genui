"""genui + a LangGraph agent with one tool. Tool calls show up in the UI as AG-UI TOOL_CALL_* events.

Run:  pip install "genui-py[fastapi]" langchain langgraph langchain-openai uvicorn
      OPENAI_API_KEY=... uvicorn langgraph_app:app --reload --port 8000
Any LangChain chat model works: MODEL=anthropic:claude-opus-5-5, MODEL=ollama:qwen3, ...
"""
import os
from pathlib import Path

from fastapi import FastAPI, Request
from langchain.agents import create_agent  # LangGraph's prebuilt agent (create_react_agent moved here)
from langchain_core.messages import ToolMessage

from genui import Library
from genui.integrations.fastapi import read_run, stream_response
from genui.stream import ToolCallArgs, ToolCallEnd, ToolCallStart, ToolResult

# spec.json is generated by the React frontend (`npm run generate` in examples/fastapi-react/frontend).
SPEC = Path(__file__).resolve().parents[1] / "fastapi-react" / "backend" / "spec.json"
library = Library.from_spec(SPEC)


def get_weather(city: str) -> str:
    """Get the current weather for a city."""
    return f"18°C and sunny in {city}"


agent = create_agent(os.environ.get("MODEL", "openai:gpt-5.5-mini"), [get_weather],
                     system_prompt=library.system_prompt())
app = FastAPI()


async def to_genui(stream):
    """stream_mode="messages" yields (message_chunk, metadata) tuples: unwrap them, turn tool-call
    chunks and tool results into genui events, and pass model text through."""
    ids: dict[int, str] = {}
    async for msg, _meta in stream:
        if isinstance(msg, ToolMessage):  # tool output: show it as a result, never as UI text
            yield ToolCallEnd(msg.tool_call_id)
            yield ToolResult(msg.tool_call_id, str(msg.content))
            continue
        for tc in getattr(msg, "tool_call_chunks", None) or []:
            idx = tc.get("index") or 0
            if tc.get("id"):
                ids[idx] = tc["id"]
                yield ToolCallStart(tc["id"], tc.get("name") or "")
            if tc.get("args") and idx in ids:
                yield ToolCallArgs(ids[idx], tc["args"])
        yield msg  # AIMessageChunk text -> genui


@app.post("/api/chat")
async def chat(request: Request):
    run = await read_run(request)
    stream = agent.astream({"messages": run.messages}, stream_mode="messages")
    return stream_response(to_genui(stream), run=run)
