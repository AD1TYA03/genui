"""genui + Pydantic AI: stream an agent's text output to OpenUI's React renderer.

Run:  pip install "genui-py[fastapi]" "pydantic-ai-slim[openai]" uvicorn
      OPENAI_API_KEY=... uvicorn pydantic_ai_app:app --reload --port 8000
Any Pydantic AI model string works: MODEL=anthropic:claude-opus-5-5, MODEL=google-gla:gemini-2.5-flash, ...
"""
import os
from pathlib import Path

from fastapi import FastAPI, Request
from pydantic_ai import Agent
from pydantic_ai.messages import ModelRequest, ModelResponse, TextPart, UserPromptPart

from genui import Library
from genui.integrations.fastapi import read_run, stream_response

# spec.json is generated by the React frontend (`npm run generate` in examples/fastapi-react/frontend).
SPEC = Path(__file__).resolve().parents[1] / "fastapi-react" / "backend" / "spec.json"
library = Library.from_spec(SPEC)

agent = Agent(os.environ.get("MODEL", "openai:gpt-5.5-mini"), instructions=library.system_prompt())
app = FastAPI()


def to_history(messages):
    """Earlier chat turns as Pydantic AI messages (the last user turn is sent as the prompt)."""
    return [ModelRequest(parts=[UserPromptPart(m["content"])]) if m["role"] == "user"
            else ModelResponse(parts=[TextPart(m["content"])])
            for m in messages if m["role"] in ("user", "assistant") and m["content"]]


async def stream_text(prompt, history):
    async with agent.run_stream(prompt, message_history=history) as result:
        async for delta in result.stream_text(delta=True):
            yield delta  # plain str -> genui


@app.post("/api/chat")
async def chat(request: Request):
    run = await read_run(request)
    history = to_history(run.messages[:-1])
    return stream_response(stream_text(run.last_user_message, history), run=run)
